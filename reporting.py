def scan_report_pdf(result: dict, model_info: dict) -> bytes:
    st = _styles()
    ml = result["ml"]
    snapshot = {
        "final_category": result["final_category"], "final_label": result["final_label"],
        "score": ml["score"], "model_name": ml["model_name"],
        "model_version": model_info.get("model_version"), "scan_time": result["timestamp"],
        "is_synthetic": model_info.get("is_synthetic"), "reasons": result["reasons"],
        "escalated_by_rules": result["escalated_by_rules"],
        "top_features": top_features(ml),
    }
    story = [_header("URLGuard AI — URL Scan Report",
                     f"Generated {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}", st),
             Spacer(1, 8),
             _kv([("Analysed URL", result["url"]),
                  ("Scheme", result["info"]["scheme"]),
                  ("Hostname", result["info"]["hostname"]),
                  ("Registered domain (approx.)", result["info"]["registered_domain"])], st),
             _p("B. Machine-learning findings (estimate)", st["h2"])]
    story += _ml_section(snapshot, st)
    story += [_p("C. Rule-based checks", st["h2"])] + _rules_section(result["rules"], st)
    story += [_p("D. Independently verified information", st["h2"])] + _verified_section(result["threat_intel"], st)
    story += [_p("Recommended safety actions", st["h2"])] + [_p(f"• {r}", st["cell"]) for r in result["recommendations"]]
    story += [Spacer(1, 8), KeepTogether([_p("Disclaimer", st["h2"]), _p(ML_DISCLAIMER, st["small"])])]
    return _build(story)


def top_features(ml: dict, limit: int = 12) -> list[dict]:
    from feature_extraction import FEATURE_DESCRIPTIONS
    shown = []
    contributing = [c["name"] for c in ml.get("contributions", []) if c["kind"] == "feature"]
    for name in contributing + list(FEATURE_DESCRIPTIONS):
        if name in ml["features"] and name not in [s["name"] for s in shown]:
            shown.append({"name": name, "label": FEATURE_DESCRIPTIONS[name], "value": ml["features"][name]})
        if len(shown) >= limit:
            break
    return shown


INCIDENT_FIELDS = [
    ("incident_category", "Incident category"),
    ("received_via", "How the link was received"),
    ("incident_datetime", "Approximate incident date/time"),
    ("money_lost", "Was money lost?"),
    ("amount_lost", "Approximate amount lost (INR)"),
    ("info_disclosed", "Personal/financial information disclosed?"),
    ("disclosed_types", "Type of information disclosed"),
    ("description", "Incident description"),
]


def incident_report_pdf(report: dict) -> bytes:
    """report = {reference, status, created_at, external_ack, data:{...}, evidence:[...]}"""
    st = _styles()
    d = report["data"]
    story = [_header("Cybercrime Incident Report — Preparation Copy",
                     f"Prepared with URLGuard AI • {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}", st),
             Spacer(1, 8),
             _kv([("Local reference", f"{report['reference']} (generated by this app; NOT a government complaint number)"),
                  ("Report status", report.get("status", "Draft")),
                  ("Created (UTC)", report.get("created_at", ""))]
                 + ([("Acknowledgement no. (entered by user)", report["external_ack"])] if report.get("external_ack") else []),
                 st),
             Spacer(1, 6), _p(NOT_SUBMITTED, st["warn"]),
             _p("A. Information supplied by the user", st["h2"]),
             _p("The statements below were entered by the user and have not been verified by URLGuard AI.", st["small"]),
             Spacer(1, 3)]
    rows = [("Suspected URL", d.get("suspected_url", ""))]
    for key, label in INCIDENT_FIELDS:
        val = d.get(key)
        if val not in (None, ""):
            rows.append((label, val))
    story.append(_kv(rows, st))

    story += [_p("B. URL analysis — machine-learning findings (estimate)", st["h2"])]
    story += _ml_section(d.get("ml", {}), st)
    story += [_p("C. Rule-based checks", st["h2"])] + _rules_section(d.get("ml", {}).get("rules", []), st)
    story += [_p("D. Independently verified information", st["h2"])] + _verified_section(d.get("threat_intel"), st)

    evidence = report.get("evidence") or d.get("evidence_meta") or []
    story += [_p("Evidence files", st["h2"])]
    if evidence:
        story.append(_grid(["File name", "Size", "SHA-256 (integrity fingerprint)"],
                           [[e.get("original_name") or e.get("name"), f"{int(e.get('size', 0)) / 1024:.1f} KB",
                             e.get("sha256", "")] for e in evidence], st, [55, 20, 105]))
        story.append(_p("Upload the original files directly on the official portal; this PDF lists file names only.",
                        st["small"]))
    else:
        story.append(_p("No evidence files were attached.", st["cell"]))

    story += _instructions(st)
    story += [Spacer(1, 8), KeepTogether([_p("Disclaimer", st["h2"]), _p(ML_DISCLAIMER, st["small"])])]
    return _build(story)
