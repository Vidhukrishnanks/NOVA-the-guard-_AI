"""
PDF generation (ReportLab) for:
  * individual scan reports
  * cybercrime incident preparation reports

Every PDF clearly separates:
  A. statements supplied by the user
  B. machine-learning findings (estimates)
  C. rule-based checks
  D. independently verified information (only if a consented lookup ran)

The local reference number is generated by this app and is NOT a government
complaint number. Nothing is ever submitted automatically.
"""
from __future__ import annotations

import io
import secrets
from datetime import datetime, timezone
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table,
                                TableStyle)

OFFICIAL_LINKS = [
    ("Report a Suspect Website or URL", "https://cybercrime.gov.in/Webform/cyber_suspect.aspx"),
    ("National Cyber Crime Reporting Portal", "https://cybercrime.gov.in/"),
]
HELPLINE = "1930"

ML_DISCLAIMER = (
    "The classification and risk score in this document were produced automatically by a "
    "machine-learning model that analysed only the text of the URL. They are estimates, not "
    "official findings, and may be wrong (false positives and false negatives are possible). "
    "The risk score is a model-based estimate, not a calibrated probability. The URL was not visited.")

NOT_SUBMITTED = (
    "This document has NOT been submitted to any authority. URLGuard AI never submits complaints "
    "automatically. You must file the complaint yourself on the official portal.")

NAVY = colors.HexColor("#0b1730")
BLUE = colors.HexColor("#0a84b8")
RED = colors.HexColor("#c62839")
AMBER = colors.HexColor("#b7791f")
GREEN = colors.HexColor("#1f8a4c")
GRID = colors.HexColor("#c9d3e3")
SHADE = colors.HexColor("#eef3fa")

CAT_COLORS = {"malicious": RED, "suspicious": AMBER, "legitimate": GREEN}


def make_reference() -> str:
    return "URLG-" + datetime.now(timezone.utc).strftime("%Y%m%d") + "-" + secrets.token_hex(3).upper()


def _styles():
    ss = getSampleStyleSheet()
    base = ParagraphStyle("base", parent=ss["Normal"], fontName="Helvetica", fontSize=9.5, leading=13)
    return {
        "base": base,
        "small": ParagraphStyle("small", parent=base, fontSize=8, leading=10.5, textColor=colors.HexColor("#4a5568")),
        "title": ParagraphStyle("title", parent=base, fontName="Helvetica-Bold", fontSize=17, leading=21,
                                textColor=colors.white),
        "subtitle": ParagraphStyle("subtitle", parent=base, fontSize=9, textColor=colors.HexColor("#cfe8ff")),
        "h2": ParagraphStyle("h2", parent=base, fontName="Helvetica-Bold", fontSize=11.5, leading=15,
                             textColor=NAVY, spaceBefore=10, spaceAfter=4),
        "cell": ParagraphStyle("cell", parent=base, fontSize=9, leading=12, alignment=TA_LEFT),
        "cellb": ParagraphStyle("cellb", parent=base, fontName="Helvetica-Bold", fontSize=9, leading=12),
        "warn": ParagraphStyle("warn", parent=base, fontSize=9, leading=12.5, textColor=RED),
    }


def _p(text, style) -> Paragraph:
    """Paragraph with user text safely escaped (ReportLab uses mini-HTML markup)."""
    safe = escape("" if text is None else str(text)).replace("\n", "<br/>")
    return Paragraph(safe, style)


def _header(title: str, subtitle: str, st) -> Table:
    t = Table([[_p(title, st["title"])], [_p(subtitle, st["subtitle"])]], colWidths=[180 * mm])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), NAVY),
        ("LEFTPADDING", (0, 0), (-1, -1), 10), ("RIGHTPADDING", (0, 0), (-1, -1), 10),
        ("TOPPADDING", (0, 0), (-1, 0), 10), ("BOTTOMPADDING", (0, -1), (-1, -1), 10),
    ]))
    return t


def _kv(rows, st, label_w=55) -> Table:
    data = [[_p(k, st["cellb"]), v if isinstance(v, Paragraph) else _p(v, st["cell"])] for k, v in rows]
    t = Table(data, colWidths=[label_w * mm, (180 - label_w) * mm])
    t.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, GRID),
        ("BACKGROUND", (0, 0), (0, -1), SHADE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    return t


def _grid(header, rows, st, widths) -> Table:
    data = [[_p(h, st["cellb"]) for h in header]] + [[_p(c, st["cell"]) for c in r] for r in rows]
    t = Table(data, colWidths=[w * mm for w in widths], repeatRows=1)
    t.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, GRID),
        ("BACKGROUND", (0, 0), (-1, 0), SHADE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    return t


def _verdict(category: str, label: str, score, st) -> Table:
    color = CAT_COLORS.get(category, BLUE)
    t = Table([[_p(f"ML assessment: {label}", ParagraphStyle("v", parent=st["base"], fontName="Helvetica-Bold",
                                                               fontSize=12, textColor=colors.white)),
                _p(f"Estimated risk score: {score} / 100", ParagraphStyle("s", parent=st["base"],
                                                                          textColor=colors.white))]],
              colWidths=[95 * mm, 85 * mm])
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), color),
                           ("TOPPADDING", (0, 0), (-1, -1), 7), ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
                           ("LEFTPADDING", (0, 0), (-1, -1), 8)]))
    return t


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 7.5)
    canvas.setFillColor(colors.HexColor("#6b7280"))
    canvas.drawString(15 * mm, 10 * mm, "Generated by URLGuard AI. ML findings are estimates, not official findings.")
    canvas.drawRightString(195 * mm, 10 * mm, f"Page {doc.page}")
    canvas.restoreState()


def _build(story) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm,
                            topMargin=14 * mm, bottomMargin=18 * mm,
                            title="URLGuard AI Report", author="URLGuard AI")
    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buf.getvalue()


def _ml_section(ml: dict, st) -> list:
    """ml = snapshot dict (see build_ml_snapshot in routes/reports.py)."""
    out = [_verdict(ml.get("final_category", ""), ml.get("final_label", ""), ml.get("score", "n/a"), st),
           Spacer(1, 4)]
    rows = [
        ("Model", ml.get("model_name", "n/a")),
        ("Model version", ml.get("model_version", "n/a")),
        ("Scan timestamp (UTC)", ml.get("scan_time", "n/a")),
    ]
    if ml.get("is_synthetic"):
        rows.append(("Training data", "SYNTHETIC demo data. Not representative of real-world accuracy."))
    if ml.get("escalated_by_rules"):
        rows.append(("Note", "Category raised to 'Suspicious' by a rule-based brand look-alike check."))
    out.append(_kv(rows, st))
    if ml.get("reasons"):
        out += [Spacer(1, 4), _p("Indicators behind this estimate (from the model's own feature contributions):", st["cellb"])]
        out += [_p(f"• {r}", st["cell"]) for r in ml["reasons"]]
    if ml.get("top_features"):
        out += [Spacer(1, 4), _grid(["Extracted URL feature", "Value"],
                                    [[f["label"], f["value"]] for f in ml["top_features"]], st, [130, 50])]
    return out


def _rules_section(rules: list, st) -> list:
    if not rules:
        return [_p("No rule-based brand impersonation indicators were triggered.", st["cell"])]
    return [_grid(["Severity", "Finding"], [[r.get("severity", "").upper(), r.get("message", "")] for r in rules],
                  st, [25, 155])]


def _verified_section(ti: dict | None, st) -> list:
    status = (ti or {}).get("status", "not_checked")
    if status in ("match", "no_match"):
        return [_kv([("Provider", ti.get("provider")), ("Checked at (UTC)", ti.get("checked_at")),
                     ("Result", ti.get("message"))], st)]
    return [_p("No independent verification was performed. "
               + ((ti or {}).get("message") or "Threat-intelligence lookup was not run."), st["cell"])]


def _instructions(st) -> list:
    out = [_p("How to report officially (India)", st["h2"])]
    out.append(_p(f"• Suspected financial cyber fraud: call {HELPLINE} immediately (National Cyber "
                  "Crime Helpline). Reporting quickly improves the chance of stopping the money.", st["warn"]))
    for name, url in OFFICIAL_LINKS:
        out.append(Paragraph(f"• {escape(name)}: <link href='{url}' color='#0a84b8'>{escape(url)}</link>",
                             st["cell"]))
    out += [_p("• Also inform your bank or payment app through its official customer-care channel.", st["cell"]),
            _p("• Keep original screenshots, messages and transaction IDs; the portal may ask you to upload them.",
               st["cell"]),
            Spacer(1, 4), _p(NOT_SUBMITTED, st["warn"])]
    return out


